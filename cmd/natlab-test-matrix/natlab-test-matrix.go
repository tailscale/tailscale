// The natlab-matrix-generator command is an experimental package for
// iterating over existing tests for natlab/vmtest, and creating a list of
// test runs based on a specified test of variations for a certain set of
// arguments for each test.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/types"
	"html/template"
	"log"
	"maps"
	"os"
	"slices"
	"strings"

	"golang.org/x/tools/go/packages"
)

type candidate struct {
	name   string
	params []string
}

type testVariation struct {
	Name         string
	TestName     string
	JoinedParams string
}

var VariationMap map[string][]string

// main parses all packages in the natlab test dir and finds candidates that
// can be used for matrix testing. See the README.md in tstest/natlab for more.
func main() {
	cfg := &packages.Config{
		Mode:  packages.NeedName | packages.NeedFiles | packages.NeedSyntax,
		Dir:   ".", // anywhere it seems?
		Tests: true,
	}
	pkgs, err := packages.Load(cfg, "./tstest/natlab/vmtest")
	if err != nil {
		log.Println(err.Error())
		return
	}
	packages.PrintErrors(pkgs)
	candidates := []candidate{}
	for _, pkg := range pkgs {
		if strings.HasSuffix(pkg.ID, ".test") {
			continue
		}
		for _, f := range pkg.Syntax {
			for _, decl := range f.Decls {
				fn, ok := decl.(*ast.FuncDecl)
				if !ok {
					continue
				}
				if !strings.HasPrefix(strings.ToLower(fn.Name.Name), "test") {
					continue
				}
				// We only care about functions, not methods.
				if fn.Recv == nil {
					var params []string
					for _, arg := range fn.Type.Params.List {
						typ := types.ExprString(arg.Type)
						params = append(params, typ)
					}
					candidates = append(candidates, candidate{fn.Name.Name, params})
				}
			}
		}
	}

	// Set up map of variations, and collect the keys for search.
	VariationMap = map[string][]string{
		"vmtest.OSImageLinux": {
			"vmtest.Ubuntu2404",
			"vmtest.Fedora43",
			"vmtest.Debian13", // debian12 takes 10x the time as debian13
		},
	}
	keys := slices.Collect(maps.Keys(VariationMap))

	// Filter out candidates that are not relevant, having an unrecognizable
	// signature.
	candidates = slices.DeleteFunc(candidates, func(c candidate) bool {
		if len(c.params) < 2 {
			return true
		}
		// First param should be "*testing.T".
		if !strings.Contains(c.params[0], "testing.T") {
			return true
		}

		for _, param := range c.params[1:] {
			if !slices.Contains(keys, param) {
				return true
			}
		}
		return false
	})

	log.Println("====== CANDIDATES FOUND ======")
	for _, c := range slices.All(candidates) {
		log.Printf("func %s(%v)\n", c.name, c.params)
	}

	var variations []testVariation

	for _, candidate := range candidates {
		results := generateTree([]string{}, candidate.params[1:])
		for _, res := range results {

			strippedParams := make([]string, len(res))
			// Clean up names for the test name.
			for i, par := range res {
				strippedParams[i] = strings.TrimPrefix(par, "vmtest.")
			}
			variations = append(variations, testVariation{
				Name:         candidate.name,
				JoinedParams: strings.Join(res, ", "),
				TestName:     fmt.Sprintf("%s_%s", candidate.name, strings.Join(strippedParams, "_")),
			})
		}
	}

	log.Println("====== VARIATIONS FOUND ======")

	for _, variation := range variations {
		log.Printf("%s: func %s(t, %s)\n", variation.TestName, variation.Name, variation.JoinedParams)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, struct {
		Package string
		Tests   []testVariation
	}{"vmtest_test", variations}); err != nil {
		log.Println(err.Error())
		return
	}

	log.Println(buf.String())
	os.WriteFile("./tstest/natlab/vmtest/matrix_generated_test.go", buf.Bytes(), 0o644)
}

func generateTree(selected, params []string) [][]string {
	if len(params) == 0 {
		return [][]string{append([]string{}, selected...)}
	}

	variations, ok := VariationMap[params[0]]
	if !ok {
		// TODO(cmol): This will end up making a broken test, handle it here, not
		// only in the filtering above.
		log.Printf("variation for %s not found, skipping\n", params[0])
		return generateTree(selected, params[1:])
	}

	var result [][]string
	for _, variation := range variations {
		withVariation := append(append([]string{}, selected...), variation)
		result = append(result, generateTree(withVariation, params[1:])...)
	}
	return result
}

var tmpl = template.Must(template.New("matrix").Parse(`// Code generated by cmd/natlab-test-matrix. DO NOT EDIT BY HAND.
// Copyright (c) Tailscale Inc & contributors
// SPDX-License-Identifier: BSD-3-Clause

package {{.Package}}

import (
	"testing"

	"tailscale.com/tstest/natlab/vmtest"
)

var testMatrix = []struct {
	name string
	fn   func(t *testing.T)
}{
{{- range .Tests}}
	{name: "{{.TestName}}", fn: func(t *testing.T) { {{.Name}}(t, {{.JoinedParams}}) }},
{{- end}}
}

func TestMatrix(t *testing.T) {
	for _, tt := range testMatrix {
		t.Run(tt.name, tt.fn)
	}
}
`))
