func FuzzForeachAttr(f *testing.F) {
	// Single MAPPED-ADDRESS attribute (IPv4): type 0x0001
	f.Add([]byte{0x00, 0x01, 0x00, 0x08, 0x00, 0x02, 0xe9, 0xd3,
		0x48, 0x45, 0x21, 0x2d})
	// Single MAPPED-ADDRESS attribute (IPv6): type 0x0001
	f.Add([]byte{0x00, 0x01, 0x00, 0x14, 0x02, 0x90, 0xce, 0x26, 0x2,
		0x0, 0xd1, 0xb4, 0xcf, 0xc1, 0x0, 0x38, 0xb2, 0x31, 0xff, 0xfe, 0xef})

	f.Fuzz(func(t *testing.T, data []byte) {
		_ = foreachAttr(data, func(_ uint16, _ []byte) error {
			return nil
		})
	})
}

